import { createHash, randomBytes } from 'node:crypto';
import { google } from 'googleapis';
import type { Auth } from 'googleapis';
import { TokenCipher } from './TokenCipher';
import type { OidcRepository, OidcUser } from './types';

/** Scopes that make the flow OpenID Connect and identify the user. */
export const OIDC_SCOPES = ['openid', 'email', 'profile'];

const PENDING_LOGIN_TTL_MS = 10 * 60 * 1000;

export interface OidcConfig {
  /** Redirect URIs of native apps (e.g. `google://oauth`) that may be used with PKCE. */
  allowedRedirectUris?: string[];
  clientId: string;
  clientSecret: string;
  /** Registered web redirect URI that points at the callback route. */
  redirectUri: string;
  /** Secret used to encrypt tokens at rest. */
  tokenEncryptionKey: string;
}

export interface BeginLoginOptions {
  /** PKCE challenge generated by a native app; otherwise the server generates the verifier. */
  codeChallenge?: string;
  loginHint?: string;
  redirectUri?: string;
  /** Local path to continue to after the login. */
  returnTo?: string;
  /** Extra Google API scopes, on top of {@link OIDC_SCOPES}. */
  scopes?: string[];
}

export interface CompleteLoginOptions {
  code: string;
  /** Required when the app generated the PKCE verifier itself (native). */
  codeVerifier?: string;
  redirectUri?: string;
  state: string;
}

export class AuthError extends Error {}

/** Only same-origin absolute paths are accepted, to prevent open redirects. */
export const safeReturnTo = (value: unknown): string | undefined =>
  typeof value === 'string' &&
  /^\/(?![/\\])/.test(value) &&
  !/[\r\n]/.test(value)
    ? value
    : undefined;

const REFRESH_TTL_MS = 30 * 24 * 3600 * 1000;

const sha256Base64Url = (v: string) =>
  createHash('sha256').update(v).digest('base64url');

/**
 * OpenID Connect relying party for Google: authorization code flow with PKCE,
 * `state` and `nonce`. The user identity is the verified `sub` claim - there are no passwords.
 * The resulting OAuth2 client can call any googleapis API the user consented to.
 */
export class OidcAuthService {
  private cipher: TokenCipher;

  constructor(
    private repo: OidcRepository,
    private config: OidcConfig,
  ) {
    this.cipher = new TokenCipher(config.tokenEncryptionKey);
  }

  /** Creates the authorization URL and remembers `state`, `nonce` and PKCE data. */
  async beginLogin(
    options: BeginLoginOptions = {},
  ): Promise<{ state: string; url: string }> {
    const redirectUri = this.checkRedirectUri(options.redirectUri);
    const scopes = Array.from(
      new Set([
        ...OIDC_SCOPES,
        ...(options.scopes ?? []).filter((s) => typeof s === 'string' && s),
      ]),
    );
    const state = randomBytes(24).toString('base64url');
    const nonce = randomBytes(24).toString('base64url');
    const codeVerifier = options.codeChallenge
      ? undefined
      : randomBytes(48).toString('base64url');
    const codeChallenge =
      options.codeChallenge ?? sha256Base64Url(codeVerifier!);
    await this.repo.savePendingLogin({
      codeVerifier,
      expiresAt: Date.now() + PENDING_LOGIN_TTL_MS,
      nonce,
      redirectUri,
      returnTo: safeReturnTo(options.returnTo),
      scopes,
      state,
    });
    const url = this.client(redirectUri).generateAuthUrl({
      access_type: 'offline',
      code_challenge: codeChallenge,
      code_challenge_method: 'S256' as Auth.CodeChallengeMethod,
      include_granted_scopes: true,
      login_hint: options.loginHint,
      prompt: 'consent',
      scope: scopes,
      state,
      // generateAuthUrl forwards unknown params to the authorization URL
      ...({ nonce } as object),
    });
    return { state, url };
  }

  /** Exchanges the code, verifies the id_token and stores the user and tokens. */
  async completeLogin(
    options: CompleteLoginOptions,
  ): Promise<{ returnTo?: string; user: OidcUser }> {
    const pending = await this.repo.takePendingLogin(options.state);
    if (!pending) throw new AuthError('Unknown or expired login');
    const redirectUri = options.redirectUri ?? this.config.redirectUri;
    if (redirectUri !== pending.redirectUri)
      throw new AuthError('Redirect URI mismatch');
    const codeVerifier = pending.codeVerifier ?? options.codeVerifier;
    if (!codeVerifier) throw new AuthError('Missing code verifier');

    const client = this.client(redirectUri);
    const { tokens } = await client.getToken({
      code: options.code,
      codeVerifier,
    });
    if (!tokens.id_token) throw new AuthError('Missing id_token');
    // Verifies signature (Google JWKS), issuer, audience and expiry.
    const ticket = await client.verifyIdToken({
      audience: this.config.clientId,
      idToken: tokens.id_token,
    });
    const claims = ticket.getPayload();
    if (!claims?.sub || !claims.email) throw new AuthError('Invalid id_token');
    if (claims.nonce !== pending.nonce) throw new AuthError('Invalid nonce');
    if (!claims.email_verified) throw new AuthError('Email is not verified');

    const existing = await this.repo.findUser(claims.sub);
    const previous = existing?.tokens
      ? (JSON.parse(this.cipher.decrypt(existing.tokens)) as Auth.Credentials)
      : undefined;
    const granted = (tokens.scope ?? '').split(' ').filter(Boolean);
    const user: OidcUser = {
      createdAt: existing?.createdAt ?? Date.now(),
      email: claims.email,
      emailVerified: true,
      id: claims.sub,
      name: claims.name,
      picture: claims.picture,
      scopes: Array.from(new Set([...(existing?.scopes ?? []), ...granted])),
      tokens: this.cipher.encrypt(
        JSON.stringify({
          ...tokens,
          refresh_token: tokens.refresh_token ?? previous?.refresh_token,
        }),
      ),
    };
    await this.repo.upsertUser(user);
    return { returnTo: pending.returnTo, user };
  }

  getUser(userId: string): Promise<OidcUser | undefined> {
    return this.repo.findUser(userId);
  }

  /** An OAuth2 client for googleapis. Refreshed tokens are persisted automatically. */
  async authorizedClient(userId: string): Promise<Auth.OAuth2Client> {
    const user = await this.repo.findUser(userId);
    if (!user?.tokens) throw new AuthError('Not authorized with Google');
    const credentials = JSON.parse(
      this.cipher.decrypt(user.tokens),
    ) as Auth.Credentials;
    const client = this.client();
    client.setCredentials(credentials);
    client.on('tokens', (fresh) => {
      void (async () => {
        const current = await this.repo.findUser(userId);
        if (!current) return;
        await this.repo.upsertUser({
          ...current,
          tokens: this.cipher.encrypt(
            JSON.stringify({ ...credentials, ...fresh }),
          ),
        });
      })().catch(() => undefined);
    });
    return client;
  }

  /** Starts a native session: returns the first refresh token of a new family. */
  async issueRefreshToken(userId: string) {
    return this.mintRefreshToken(userId, randomBytes(16).toString('hex'));
  }

  /** Single-use rotation: the presented token is consumed and a new one of the same family is returned. */
  async rotateRefreshToken(token: string) {
    const old = await this.repo.takeRefreshToken(sha256Base64Url(token));
    if (!old) throw new AuthError('Invalid refresh token');
    return this.mintRefreshToken(old.userId, old.familyId);
  }

  /** False once the native session was logged out (or its refresh token expired). */
  isSessionActive(familyId: string): Promise<boolean> {
    return this.repo.isFamilyActive(familyId);
  }

  async revokeSession(familyId: string): Promise<void> {
    await this.repo.deleteRefreshTokens({ familyId });
  }

  private async mintRefreshToken(userId: string, familyId: string) {
    const refreshToken = randomBytes(32).toString('base64url');
    await this.repo.saveRefreshToken({
      expiresAt: Date.now() + REFRESH_TTL_MS,
      familyId,
      hash: sha256Base64Url(refreshToken),
      userId,
    });
    return { familyId, refreshToken, userId };
  }

  /** Revokes the grant at Google and forgets the tokens. The user record is kept. */
  async logout(userId: string): Promise<void> {
    await this.repo.deleteRefreshTokens({ userId });
    const user = await this.repo.findUser(userId);
    if (!user?.tokens) return;
    const { access_token, refresh_token } = JSON.parse(
      this.cipher.decrypt(user.tokens),
    ) as Auth.Credentials;
    const token = refresh_token ?? access_token;
    if (token)
      await this.client()
        .revokeToken(token)
        .catch(() => undefined);
    await this.repo.upsertUser({ ...user, scopes: [], tokens: undefined });
  }

  private checkRedirectUri(redirectUri = this.config.redirectUri): string {
    if (
      redirectUri !== this.config.redirectUri &&
      !this.config.allowedRedirectUris?.includes(redirectUri)
    )
      throw new AuthError('Redirect URI not allowed');
    return redirectUri;
  }

  private client(redirectUri = this.config.redirectUri): Auth.OAuth2Client {
    return new google.auth.OAuth2(
      this.config.clientId,
      this.config.clientSecret,
      redirectUri,
    );
  }
}
